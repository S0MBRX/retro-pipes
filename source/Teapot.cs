    static double[] Basis(double t) { double q=1-t; return new[]{q*q*q,3*t*q*q,3*t*t*q,t*t*t}; }
    static double[] Derivative(double t) { double q=1-t; return new[]{-3*q*q,3*q*q-6*t*q,6*t*q-3*t*t,3*t*t}; }
    static void Vertex(int patch,double u,double v,int rotation,bool mirror) {
        var bu=Basis(u); var bv=Basis(v); var du=Derivative(u); var dv=Derivative(v);
        double[] p=new double[3],a=new double[3],b=new double[3];
        for(int i=0;i<4;i++) for(int j=0;j<4;j++) for(int k=0;k<3;k++) {
            double c=points[patches[patch,i*4+j],k];
            p[k]+=bu[i]*bv[j]*c; a[k]+=du[i]*bv[j]*c; b[k]+=bu[i]*dv[j]*c;
        }
        double nx=b[1]*a[2]-b[2]*a[1],ny=b[2]*a[0]-b[0]*a[2],nz=b[0]*a[1]-b[1]*a[0];
        if(nx*nx+ny*ny+nz*nz<1e-12) { nx=ny=0; nz=p[2]>1.5?1:-1; }
        if(mirror) { p[1]=-p[1]; ny=-ny; }
        for(int i=0;i<rotation;i++) { double temp=p[0]; p[0]=-p[1]; p[1]=temp; temp=nx; nx=-ny; ny=temp; }
        GL.glNormal3d(nx,nz,-ny); GL.glVertex3d(p[0],p[2]-1.575,-p[1]);
    }
